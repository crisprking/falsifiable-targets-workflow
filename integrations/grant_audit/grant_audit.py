#!/usr/bin/env python3
"""ft-grant-audit — pre-submission grant rigor checklist.

Walks a PI through writing a claim YAML for a grant proposal's primary
target hypothesis, runs the audit, and emits a one-page report
suitable for the grant's Rigor & Reproducibility section.

Use case: an R01/ERC/MRC PI is writing a grant claiming "we will
validate target X as a therapeutic intervention point for disease Y."
Before submission, they want a structured falsifiability check that:

  (a) Identifies the cheapest experiment that would falsify the
      hypothesis if it's wrong (this becomes the grant's go/no-go
      milestone)
  (b) Produces a citable audit record (ruleset SHA + report JSON) for
      the Rigor section
  (c) Pre-empts the reviewer's "but how would you falsify this?"
      question.

Two usage modes:

    # Interactive (questionnaire mode)
    python grant_audit.py --interactive --output my_grant_claim.yaml

    # From an existing claim
    python grant_audit.py --claim my_grant_claim.yaml --report grant_audit.md

The output Markdown report is structured for copy-paste into the
grant's Rigor & Reproducibility section.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path


INTERACTIVE_QUESTIONS = [
    ("target_symbol", "Target gene symbol (HGNC convention, e.g. TYK2): ", True),
    ("uniprot_id", "UniProt accession (e.g. P29597) [optional, leave blank if none]: ", False),
    ("indication", "Disease/indication name (e.g. 'psoriasis'): ", True),
    ("mechanism", "One-sentence mechanism of action: ", True),
    ("citation_pmid", "Primary supporting PubMed ID [optional]: ", False),
    ("citation_doi", "Primary supporting DOI [optional]: ", False),
    ("author", "PI name (for the claim record): ", False),
]

CLAIM_TYPE_GUIDE = """
Claim type guide:
  - validated_mechanism  → existing clinical/preclinical precedent (statin/HMGCR-class)
  - novel_target         → CRISPR/OMICS hit, not yet wet-lab validated
  - chemistry_series     → claim is about a chemical series, not a single target
  - extraordinary_claim  → contradicts current paradigm (e.g. STAP cells, arsenic life)
"""


def interactive_claim(output_path: Path) -> int:
    """Walk the user through claim creation, then write YAML."""
    print("\n=== Falsifiability self-audit: grant claim builder ===\n")
    print("Answer each question. Press Ctrl-C to abort.\n")

    answers = {}
    for key, prompt, required in INTERACTIVE_QUESTIONS:
        while True:
            val = input(prompt).strip()
            if val or not required:
                if val:
                    answers[key] = val
                break
            print("  This field is required.")

    print(CLAIM_TYPE_GUIDE)
    valid_types = ["validated_mechanism", "novel_target", "chemistry_series", "extraordinary_claim"]
    while True:
        ct = input(f"Claim type {valid_types}: ").strip()
        if ct in valid_types:
            answers["claim_type"] = ct
            break
        print(f"  Must be one of {valid_types}")

    today = time.strftime("%Y-%m-%d")
    answers.setdefault("date", today)

    # Render
    lines = [
        "# Grant claim self-audit",
        f"# Generated by ft-grant-audit on {today}",
        "# Audit instructions: see the 'Next steps' section of grant_audit.md",
        "",
        "claim:",
    ]
    field_order = ["target_symbol", "uniprot_id", "indication", "mechanism",
                   "claim_type", "citation_pmid", "citation_doi", "author", "date"]
    for k in field_order:
        v = answers.get(k)
        if v:
            lines.append(f"  {k}: {v!r}")

    output_path.write_text("\n".join(lines) + "\n")
    print(f"\nClaim written to {output_path}")
    print(f"Next: python grant_audit.py --claim {output_path} --report grant_audit.md")
    return 0


def run_audit(claim_path: Path, json_out: Path, offline: bool = False) -> dict | None:
    """Invoke ft-audit; return the parsed JSON report or None on failure.

    Note: ft-audit returns non-zero on non-SURVIVED verdicts (it's a CI
    contract). We only treat the run as failed if the JSON file wasn't
    produced — the verdict itself is meaningful regardless of exit code.
    """
    cmd = ["ft-audit", str(claim_path), "--json-out", str(json_out)]
    if offline:
        cmd.append("--no-live")
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    if json_out.exists():
        try:
            return json.loads(json_out.read_text())
        except json.JSONDecodeError as e:
            print(f"Audit JSON malformed: {e}", file=sys.stderr)
            return None
    print(f"ft-audit produced no report (exit {result.returncode}):", file=sys.stderr)
    print(result.stderr[-1000:], file=sys.stderr)
    return None


def report_markdown(claim_path: Path, report: dict) -> str:
    """Emit the one-page Markdown report for the grant's Rigor section."""
    claim = report.get("claim", {})
    verdict = report.get("verdict", "UNKNOWN")
    ruleset_sha = report.get("ruleset_sha256", "unknown")[:16]
    tool_version = (report.get("tool") or {}).get("version", "unknown")

    # Collect caveats from per_rule structure — real engine puts them per-rule.
    substantive_caveats = []  # list of dicts: {rule_id, text}
    operational_notes = []
    for r in report.get("per_rule") or []:
        for c in r.get("caveats") or []:
            entry = {"rule_id": r["rule_id"], "text": c.get("text", "?")}
            if c.get("kind") == "substantive":
                substantive_caveats.append(entry)
            else:
                operational_notes.append(entry)

    # Cheapest falsification: the most informative field for grant readers.
    cheapest = report.get("cheapest_falsification")

    verdict_emoji = {
        "SURVIVED": "✓",
        "FALSIFIED_WITH_CAVEATS": "⚠",
        "FALSIFIED": "✗",
        "INSUFFICIENT_DATA": "?",
    }.get(verdict, "?")

    md = []
    md.append(f"# Pre-submission Falsifiability Audit\n")
    md.append(f"**Target:** {claim.get('target_symbol', 'unknown')}  ")
    md.append(f"**Indication:** {claim.get('indication', 'unknown')}  ")
    md.append(f"**Claim type:** {claim.get('claim_type', 'unknown')}  ")
    md.append(f"**Audit tool:** falsifiable-targets v{tool_version}  ")
    md.append(f"**Ruleset SHA:** `{ruleset_sha}...`  ")
    md.append(f"**Audit date:** {time.strftime('%Y-%m-%d')}\n")

    md.append(f"## Verdict: {verdict_emoji} **{verdict}**\n")

    if verdict == "SURVIVED":
        md.append(
            "The claim, as written, passes all applicable rules in the "
            "falsifiability audit. **This does not mean the hypothesis is true** — "
            "it means the publicly-available evidence does not currently falsify "
            "the claim under the v1.2.0 ruleset.\n"
        )
    elif verdict == "FALSIFIED_WITH_CAVEATS":
        md.append(
            f"The claim survives at the top level but is flagged with "
            f"{len(substantive_caveats)} substantive caveat(s). Each caveat below "
            f"represents a specific weakness that the grant's Aims should "
            f"address explicitly.\n"
        )
    elif verdict == "FALSIFIED":
        md.append(
            "The claim is falsified by the public evidence as encoded. "
            "**This is a strong signal to revise the hypothesis before submission.** "
            "The cheapest falsifier (below) is the experiment that already "
            "argues against the claim — incorporating its result into the "
            "grant's Background section is recommended.\n"
        )
    else:
        md.append(
            "Insufficient public data was available to render a verdict. "
            "This is itself informative: the grant should explicitly address "
            "the data scarcity in its Significance section, and the proposed "
            "Aims should include the data-gathering experiments that would "
            "make this claim auditable.\n"
        )

    # Cheapest falsification — the headline finding
    if cheapest:
        md.append(f"## Cheapest falsification experiment\n")
        if isinstance(cheapest, dict):
            md.append(f"**Rule:** `{cheapest.get('rule_id', 'unknown')}`  ")
            md.append(f"**Experiment tier:** `{cheapest.get('experiment_tier', 'unknown')}`  ")
            if cheapest.get("rationale") or cheapest.get("description"):
                md.append(f"\n{cheapest.get('rationale') or cheapest.get('description')}\n")
        else:
            md.append(f"`{cheapest}`\n")
        md.append(
            "\n> **Suggested action:** include this experiment as an "
            "explicit go/no-go milestone in the grant's Specific Aims. "
            "Failure at this milestone terminates the project before larger "
            "investments (animal studies, chemistry, lead optimization).\n"
        )

    # Substantive caveats
    if substantive_caveats:
        md.append(f"## Substantive caveats ({len(substantive_caveats)})\n")
        md.append("Each of these is a specific weakness reviewers will likely identify. "
                 "Address each in the grant's Approach section.\n")
        for c in substantive_caveats:
            md.append(f"- **[{c['rule_id']}]** {c['text']}")
        md.append("")

    # Operational notes
    if operational_notes:
        md.append(f"## Operational notes ({len(operational_notes)})\n")
        md.append("Data gaps or rules that abstained. Not critical, but worth filling in.\n")
        for n in operational_notes:
            md.append(f"- **[{n['rule_id']}]** {n['text']}")
        md.append("")

    # Methods-section text the PI can copy-paste
    md.append("## Suggested text for the grant's Rigor & Reproducibility section\n")
    md.append("```")
    md.append(
        f"Prior to submission we performed a structured falsifiability audit "
        f"of the primary target hypothesis (target: {claim.get('target_symbol')}, "
        f"indication: {claim.get('indication')}) using the falsifiable-targets "
        f"framework (v{tool_version}, ruleset SHA {ruleset_sha}...). "
    )
    if verdict == "SURVIVED":
        md.append(
            "The claim survived all applicable rules. The audit JSON and "
            "ruleset SHA are included in the Supplementary Materials for "
            "reproducibility."
        )
    elif verdict in ("FALSIFIED_WITH_CAVEATS", "FALSIFIED"):
        cheapest_id = (
            cheapest.get("rule_id") if isinstance(cheapest, dict) and cheapest
            else (substantive_caveats[0]["rule_id"] if substantive_caveats else "unspecified")
        )
        first_caveats = "; ".join(c["text"] for c in substantive_caveats[:3])
        md.append(
            f"The audit identified the following weaknesses, which we "
            f"address explicitly in the Aims: {first_caveats}. "
            f"The cheapest falsification experiment ({cheapest_id}) "
            f"is included as an explicit go/no-go milestone in Aim 1."
        )
    md.append("```\n")

    md.append(f"## Audit record\n")
    md.append("Include the full JSON report (machine-readable, reproducible) "
              "in the grant's supplementary materials:\n")
    md.append(f"- Audit JSON: `{claim_path.stem}_audit.json`")
    md.append(f"- Ruleset SHA: `{report.get('ruleset_sha256', '?')}`")
    md.append(f"- Tool version: `{tool_version}`")
    md.append(f"- Reproduced by: `ft-audit {claim_path.name} --json-out <report.json>`\n")

    return "\n".join(md)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--interactive", action="store_true",
                   help="Walk through claim creation interactively.")
    p.add_argument("--claim", type=Path,
                   help="Path to existing claim YAML.")
    p.add_argument("--output", type=Path, default=Path("grant_claim.yaml"),
                   help="Path to write claim YAML in --interactive mode "
                        "(default: grant_claim.yaml).")
    p.add_argument("--report", type=Path, default=Path("grant_audit.md"),
                   help="Path to write the Markdown report (default: grant_audit.md).")
    p.add_argument("--offline", action="store_true",
                   help="Pass --no-live to ft-audit (fixtures only).")
    args = p.parse_args(argv)

    if args.interactive:
        return interactive_claim(args.output)

    if not args.claim or not args.claim.exists():
        print("Either --interactive or --claim <path> is required.", file=sys.stderr)
        return 2

    json_out = args.claim.with_suffix(".audit.json")
    print(f"Running ft-audit on {args.claim}...")
    report = run_audit(args.claim, json_out, offline=args.offline)
    if report is None:
        return 1

    md = report_markdown(args.claim, report)
    args.report.write_text(md)

    verdict = report.get("verdict", "UNKNOWN")
    print(f"\nVerdict: {verdict}")
    print(f"Report:  {args.report}")
    print(f"JSON:    {json_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
